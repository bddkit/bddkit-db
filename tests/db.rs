#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn a_procedure_is_called_with_its_arguments() {
    require_bddkit!();
    let guard = setup().await;
    sqlx::any::install_default_drivers();
    let pool = AnyPool::connect(&test_dsn()).await.expect("connect");
    // `sqlx::query` prepares, which MySQL refuses for `CREATE PROCEDURE`.
    let ddl = match engine() {
        Engine::Postgres => vec![
            "CREATE OR REPLACE PROCEDURE apibdd_it.rename_company(p_id bigint, p_name text) \
             LANGUAGE sql AS $$ UPDATE apibdd_it.companies SET name = p_name WHERE id = p_id $$",
        ],
        Engine::MySql | Engine::MariaDb => vec![
            "DROP PROCEDURE IF EXISTS rename_company",
            "CREATE PROCEDURE rename_company(p_id BIGINT, p_name VARCHAR(255)) \
             UPDATE companies SET name = p_name WHERE id = p_id",
        ],
    };
    for statement in ddl {
        sqlx::raw_sql(statement)
            .execute(&pool)
            .await
            .unwrap_or_else(|e| panic!("{statement}: {e}"));
    }
    pool.close().await;
    let src = "\
Feature: procedure
  Scenario: call it
    Given I have \"companies\" with \"slug: proc-co\"
    When I call procedure \"rename_company\" with \"p_id: <<last_insert_id_companies>>, p_name: Renamed\"
    Then I should have \"companies\" with \"id: <<last_insert_id_companies>>, name: Renamed\"
";
    let out = run_feature(src, &guard);
    assert!(out.status.success(), "{}", combined(&out));
}
